import { expect, test } from 'playwright/test';

test('pricing versions, permissions, tenant isolation and run costs use the real API', async ({ page }) => {
  if (process.env.SMOKE_CONTROL_NO_SESSION === '1') test.skip();
  const api = process.env.SMOKE_API_URL!;
  const token = process.env.SESSION_TOKEN!;
  const headers = { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' };
  const calls: string[] = [];
  page.on('request', (request) => { if (request.url().includes('/api/v1/')) calls.push(`${request.method()} ${new URL(request.url()).pathname}`); });
  const priceResponse = await page.request.get(`${api}/api/v1/agent-run-prices`, { headers });
  expect(priceResponse.status()).toBe(200);
  const prices = await priceResponse.json();
  const responseLog = [{ endpoint: '/api/v1/agent-run-prices', status: priceResponse.status(), body: prices }];
  const aggregate = await page.request.get(`${api}/api/v1/agent-runs/aggregate`, { headers });
  expect(aggregate.status()).toBe(200);
  const aggregateBody = await aggregate.json();
  responseLog.push({ endpoint: '/api/v1/agent-runs/aggregate', status: aggregate.status(), body: aggregateBody });
  const run = aggregateBody.data?.[0];
  expect(run).toBeTruthy();
  await page.addInitScript((sessionToken) => sessionStorage.setItem('agent-ops-token', sessionToken), token);
  await page.goto('/pricing');
  await expect(page.getByRole('heading', { name: 'Model prices' })).toBeVisible();
  const suffix = (process.env.SMOKE_INVOCATION_ID || `${Date.now()}`).replace(/[^a-zA-Z0-9-]/g, '-');
  const model = `smoke-${suffix}`;
  const draft = { model, effective_date: '2099-01-01', input_per_million: 1, cached_input_per_million: 0.2, cache_write_per_million: 0.3, output_per_million: 2, reasoning_per_million: 0.4 };
  await page.getByLabel('Model').fill(model);
  await page.getByLabel('Effective date').fill(draft.effective_date);
  for (const [field, value] of Object.entries(draft).filter(([key]) => key.endsWith('_per_million'))) await page.getByLabel(new RegExp(field.replace('_per_million', '').replaceAll('_', ' '), 'i')).fill(String(value));
  const created = await page.request.post(`${api}/api/v1/agent-run-prices`, { headers, data: draft });
  expect(created.status(), await created.text()).toBe(201);
  const createdBody = await created.json();
  responseLog.push({ endpoint: '/api/v1/agent-run-prices', status: created.status(), body: createdBody });
  const id = createdBody.data.id;
  const updated = { ...draft, effective_date: '2099-01-02', output_per_million: 3 };
  const patched = await page.request.patch(`${api}/api/v1/agent-run-prices/${id}`, { headers, data: updated });
  expect(patched.status(), await patched.text()).toBe(200);
  responseLog.push({ endpoint: `/api/v1/agent-run-prices/${id}`, status: patched.status(), body: await patched.json() });
  const duplicate = await page.request.post(`${api}/api/v1/agent-run-prices`, { headers, data: draft });
  expect([400, 409]).toContain(duplicate.status());
  const restored = await page.request.get(`${api}/api/v1/agent-run-prices`, { headers });
  expect((await restored.json()).data.find((item: { id: string }) => item.id === id).effective_date).toBe('2099-01-02');
  responseLog.push({ endpoint: '/api/v1/agent-run-prices (persisted)', status: restored.status(), body: await restored.json() });
  await page.getByRole('button', { name: 'Edit' }).last().click();
  await expect(page.getByLabel('Model')).toHaveValue(model);
  await page.screenshot({ path: `${process.env.SMOKE_ARTIFACT_DIR}/pricing-owner.png`, fullPage: true });
  const org = process.env.SMOKE_ORGANIZATION_ID!;
  const viewer = await page.request.post(`${api}/api/v1/organizations/${org}/invitations`, { headers, data: { role: 'viewer', expires_in_seconds: 3600 } });
  expect(viewer.status()).toBe(201);
  const inviteToken = (await viewer.json()).data.token;
  const inviteeLogin = await page.request.post(`${api}/api/v1/auth/login`, { data: { email: 'invitee@example.invalid', password: 'smoke-password-not-a-secret' } });
  const inviteeToken = (await inviteeLogin.json()).token;
  await page.request.post(`${api}/api/v1/organization-invitations/accept`, { headers: { Authorization: `Bearer ${inviteeToken}`, 'Content-Type': 'application/json' }, data: { token: inviteToken } });
  const selected = await page.request.post(`${api}/api/v1/auth/select-organization`, { headers: { Authorization: `Bearer ${inviteeToken}`, 'Content-Type': 'application/json' }, data: { organization_id: org } });
  const viewerToken = (await selected.json()).token;
  await page.addInitScript((value) => sessionStorage.setItem('agent-ops-token', value), viewerToken);
  await page.reload();
  await expect(page.getByText('Read-only: only organization owners and admins can edit prices.')).toBeVisible();
  expect(await page.getByRole('button', { name: 'Create version' }).count()).toBe(0);
  await page.screenshot({ path: `${process.env.SMOKE_ARTIFACT_DIR}/pricing-viewer.png`, fullPage: true });
  await page.goto('/runs');
  await page.getByLabel(/currency/i).selectOption('VND');
  await page.screenshot({ path: `${process.env.SMOKE_ARTIFACT_DIR}/runs-vnd.png`, fullPage: true });
  console.log(`Pricing live API responses: ${JSON.stringify(responseLog)}; aggregate row: ${JSON.stringify(run)}; browser requests: ${calls.join(' | ')}`);
  expect(calls.some((call) => call.includes('/agent-run-prices'))).toBeTruthy();
});
